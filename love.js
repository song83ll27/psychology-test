const questionScreen = document.getElementById("love-question");
const resultScreen = document.getElementById("love-result");
const resultTitle = document.getElementById("love-result-title");
const resultDetails = document.getElementById("love-result-details");
let selectedIndex = 0;

function showLoveResult(index) {
  selectedIndex = index;
  const result = loveResults[index];
  resultTitle.textContent = result.title;
  resultDetails.replaceChildren();

  const intro = document.createElement("p");
  intro.textContent = result.intro;
  resultDetails.appendChild(intro);

  result.sections.forEach(([heading, paragraph]) => {
    const section = document.createElement("section");
    section.className = "love-result-section";
    const title = document.createElement("h3");
    title.textContent = heading;
    const text = document.createElement("p");
    text.textContent = paragraph;
    section.append(title, text);
    resultDetails.appendChild(section);
  });

  questionScreen.classList.add("hidden");
  resultScreen.classList.remove("hidden");
  window.scrollTo({ top: 0, behavior: "smooth" });
}

document.querySelectorAll("[data-answer]").forEach(button => {
  button.addEventListener("click", () => showLoveResult(Number(button.dataset.answer)));
});

function backHome() {
  window.location.href = "index.html";
}
document.getElementById("love-home").addEventListener("click", backHome);
document.getElementById("love-result-home").addEventListener("click", backHome);
document.getElementById("love-retry").addEventListener("click", () => {
  resultScreen.classList.add("hidden");
  questionScreen.classList.remove("hidden");
  window.scrollTo({ top: 0, behavior: "smooth" });
});
document.getElementById("love-share").addEventListener("click", () => {
  const text = `恋愛心理テストの結果は「${loveResults[selectedIndex].title}」でした！\n${location.href}`;
  window.open(`https://line.me/R/msg/text/?${encodeURIComponent(text)}`, "_blank");
});
